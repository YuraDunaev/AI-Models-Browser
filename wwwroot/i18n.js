let I18N_LANG = "en";

function i18nNormalize(lang) {
  if (!lang) return "en";
  const l = String(lang).toLowerCase().split(/[-_]/)[0];
  return Object.prototype.hasOwnProperty.call(I18N_DICT, l) ? l : "en";
}

function i18nLang() { return I18N_LANG; }

function i18nKeys() { return Object.keys(I18N_DICT.en); }

function t(key, vars) {
  const dict = I18N_DICT[I18N_LANG] || I18N_DICT.en;
  let text = dict[key];
  if (text === undefined) text = I18N_DICT.en[key];
  if (text === undefined) return key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m);
  }
  return text;
}

function i18nApply(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  scope.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
}

function i18nSetLang(lang) {
  I18N_LANG = i18nNormalize(lang);
  document.documentElement.setAttribute("lang", I18N_LANG);
  i18nApply(document);
  return I18N_LANG;
}

function i18nLocale() {
  const map = { en: "en-US", ru: "ru-RU", de: "de-DE", fr: "fr-FR", es: "es-ES", zh: "zh-CN" };
  return map[I18N_LANG] || "en-US";
}

window.i18n = {
  setLang: i18nSetLang,
  getLang: i18nLang,
  t: t,
  apply: i18nApply,
  locale: i18nLocale,
  langs: I18N_LANG_NAMES,
  supported: Object.keys(I18N_DICT),
  keys: i18nKeys(),
  dict: I18N_DICT,
};
